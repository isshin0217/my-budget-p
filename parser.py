"""
parser.py
카드 승인/취소 문자(SMS) 한 건을 구조화된 데이터로 변환한다.

지원 형식 (신한카드 예시):
  [Web 발신]
  신한카드(1234)승인 홍*동 94,400원(일시불)07/01 19:55 폴리스 유한
  [Web발신]
  신한카드 (1234) 매출취소 홍*동 29,902원 07/12 네이버페이

반환 dict 필드:
  card      : 카드사 (예: 신한카드)
  last4     : 카드 뒷 4자리 (예: 1234)
  kind      : 승인 / 취소
  name      : 명의자(마스킹된 이름)
  amount    : 금액(정수). 취소는 음수로 저장해 합계가 맞도록 함.
  paytype   : 일시불 / 3개월 등 (없으면 '')
  datetime  : ISO 문자열 (YYYY-MM-DD HH:MM). 문자에 연도가 없어 현재연도로 보정.
  merchant  : 가맹점명 (예: 폴리스 유한)
  category  : 가맹점 키워드로 자동 분류한 카테고리
  raw       : 원문(정규화 후)
"""

import re
from datetime import datetime

# 가맹점 키워드 → 카테고리 (필요에 따라 자유롭게 추가)
# 순서가 곧 우선순위다. 먼저 걸리는 카테고리가 이긴다.
# '배달'은 '식비'보다, '택시'는 '교통'보다 **반드시 앞에** 와야 한다.
# 뒤에 두면 배민이 식비로, 택시가 교통으로 먼저 걸려 새 카테고리가 영영 안 쓰인다.
CATEGORY_RULES = [
    ("배달",   ["배달", "배민", "우아한형제들", "요기요", "쿠팡이츠", "uber eats", "ubereats"]),
    # 카카오T는 사실상 택시다. '카카오모빌리티'로 찍히는 건 주차·대리도 섞여 '교통'에 둔다.
    # 'uber' 는 Uber Eats 가 위 '배달'에 먼저 걸리므로 여기서는 승차만 남는다.
    ("택시",   ["택시", "카카오t", "uber"]),
    ("식비",   ["김밥", "식당", "분식", "국밥", "고기", "치킨", "피자", "버거", "맥도날드",
               "롯데리아", "food", "레스토랑",
               "이자카야", "호프", "포차", "주점", "술집", "곱창", "막창", "초밥", "스시",
               "파스타", "칼국수", "냉면", "떡볶이", "베이커리", "제과", "빵"]),
    # '매머드'는 문자에 '커피' 없이 상호만 찍혀 와서 따로 넣어야 잡힌다.
    # 표기가 '매머드'/'메머드' 둘 다 돌아다녀서 양쪽을 넣는다.
    ("카페",   ["스타벅스", "카페", "커피", "이디야", "투썸", "메가", "매머드", "메머드",
               "커피빈", "coffee", "빽다방"]),
    ("마트/편의점", ["이마트", "홈플러스", "롯데마트", "gs25", "cu", "세븐일레븐", "emart",
                 "코스트코", "노브랜드", "편의점", "마트"]),
    ("교통",   ["카카오모빌리티", "코레일", "ktx", "지하철", "버스", "주유",
               "s-oil", "gs칼텍스", "하이패스", "주차"]),
    ("온라인쇼핑", ["쿠팡", "네이버페이", "11번가", "지마켓", "옥션", "aliexpress", "amazon"]),
    ("통신",   ["skt", "kt", "lg유플러스", "lgu", "통신", "아이즈비전"]),
    ("의료",   ["병원", "약국", "의원", "치과", "한의원", "clinic"]),
    ("구독/디지털", ["netflix", "넷플릭스", "youtube", "유튜브", "google", "apple.com", "icloud",
                 "spotify", "멜론", "지니"]),
    ("의류/미용", ["무신사", "올리브영", "미용실", "헤어", "네일", "지그재그", "에이블리", "유니클로",
                 "zara", "h&m", "스파오", "아디다스", "나이키", "화장품", "이니스프리"]),
    ("생필품",   ["다이소", "생활용품", "문구", "세탁", "철물", "홈센터"]),
    ("경조사/선물", ["화환", "꽃", "플라워", "선물", "기프트", "축의", "조의"]),
    ("주거/고정", ["관리비", "월세", "임대", "전기", "가스", "수도", "보험", "헬스", "피트니스", "학원"]),
]

# 카테고리 → 돈이 나가는 리듬. 리포트에서 고정/주기/일상으로 나눠 본다.
#   고정 : 내 의지로 줄이기 어려운 매달 같은 돈
#   주기 : 주 단위로 몰아서 쓰는 돈 (장보기, 데이트, 주유)
#   일상 : 매일 조금씩 새는 돈 (밥, 카페, 교통)
PERIOD_BY_CATEGORY = {
    "식비": "일상",
    "카페": "일상",
    "교통": "일상",
    "배달": "일상",
    "택시": "일상",
    "마트/편의점": "주기",
    "온라인쇼핑": "주기",
    "의류/미용": "주기",
    "생필품": "주기",
    "의료": "주기",
    "경조사/선물": "주기",
    "통신": "고정",
    "구독/디지털": "고정",
    "주거/고정": "고정",
    "미분류": "주기",
}


def period_of(category: str) -> str:
    """카테고리의 기본 주기. 고정비 자동 감지가 이 값을 덮어쓸 수 있다."""
    return PERIOD_BY_CATEGORY.get(category, "주기")


def classify(merchant: str) -> str:
    """가맹점명을 소문자로 비교해 카테고리를 붙인다. 못 찾으면 '미분류'."""
    m = (merchant or "").lower()
    for category, keywords in CATEGORY_RULES:
        if any(k.lower() in m for k in keywords):
            return category
    return "미분류"


# 핵심 파싱 정규식. 카드사마다 표기가 달라 느슨하게 잡는다.
#   신한카드(1234)승인 홍*동 94,400원(일시불)07/01 19:55 폴리스 유한
#   우리(5678)승인 김*수님 36,400원 일시불 07/20 21:54 유한회사 미소
#   신한카드 (1234) 매출취소 홍*동 29,902원 07/12 네이버페이
_APPROVAL_RE = re.compile(
    r'(?P<card>[^\s(]{1,12})\s*\((?P<last4>\d{3,4})\)\s*'  # 신한카드( / 우리(
    # 취소 문자는 '매출취소' 처럼 앞에 말이 더 붙어 온다. 접두사를 받아주지 않으면
    # 취소가 통째로 안 잡혀 환불이 영영 반영되지 않는다.
    r'(?P<kind>(?:매출|해외)?(?:승인|취소))\s*'              # 승인 / 취소 / 매출취소
    r'(?P<name>\S+?)\s+'                                    # 홍*동 / 김*수님
    r'(?P<amount>[\d,]+)\s*원\s*'                           # 94,400원
    # 결제유형은 (일시불) 처럼 괄호에 싸이기도 하고 그냥 붙어 오기도 한다.
    r'(?:\(?\s*(?P<paytype>[^()/]*?)\s*\)?\s*)?'
    # 날짜 앞의 (?<!\d) 는 파이썬에서는 없어도 되지만 Code.gs 와 글자 그대로 맞춰 둔다.
    # V8 은 (?:...)? 안의 그룹이 빈 채로 도는 걸 거부해서, 결제유형이 없는 문자에서
    # paytype 이 월의 첫 자리를 먹어 12/25 를 2/25 로 읽었다. 파이썬 re 는 빈 반복을
    # 허용해 멀쩡했고, 그래서 check_port 가 두 쪽을 같다고 판정했다 — 패턴을 벌려 두면
    # 그 대조가 또 거짓 통과를 낸다.
    #
    # 취소 문자에는 시각이 아예 없다(07/12 네이버페이). 시각을 필수로 두면 이런 문자가
    # 전부 파싱 실패로 빠지므로 선택으로 둔다. 없으면 00:00 으로 본다.
    r'(?<!\d)(?P<mmdd>\d{1,2}/\d{1,2})(?:\s+(?P<hm>\d{1,2}:\d{2}))?'   # 07/01 19:55 / 07/12
    r'\s*(?P<merchant>.*)$'                                 # 폴리스 유한
)

# 카드번호가 아예 없는 형식. 현대카드가 이렇게 보낸다.
#   현대카드Z ontact 승인 홍*동 10,000원 일시불 07/27 17:10 모바일티머니선 누적206,250원
#
# 위 정규식은 '(네자리)' 를 기준점으로 삼아 문장을 끊는데, 이 문자엔 괄호가 없어
# 통째로 파싱 실패한다. 그래서 기준점을 '승인/취소' 로 바꾼 패턴을 따로 둔다.
# 이쪽이 훨씬 헐거우므로 위 정규식이 실패했을 때만 쓴다.
_APPROVAL_NO_NUM_RE = re.compile(
    r'^(?P<card>.{1,20}?)\s*'                               # 현대카드Z ontact
    r'(?P<kind>(?:매출|해외)?(?:승인|취소))\s+'
    r'(?P<name>\S+?)\s+'
    r'(?P<amount>[\d,]+)\s*원\s*'
    r'(?:\(?\s*(?P<paytype>[^()/]*?)\s*\)?\s*)?'
    r'(?<!\d)(?P<mmdd>\d{1,2}/\d{1,2})(?:\s+(?P<hm>\d{1,2}:\d{2}))?'   # 위와 같은 이유
    r'\s*(?P<merchant>.*)$'
)

# 외화로 찍히는 해외결제. 현대카드가 이렇게 보낸다.
#   현대 대한항공120 해외승인 홍*동님 10/17 16:40 JPY 2,000.00 UBER*TRIPHELP.UBER.COM
#   현대 대한항공120 해외승인 취소 홍*동님 10/17 16:41 JPY 1,258.00 UBER*PENDING
#
# 원화로 바꾸는 환율은 Code.gs(GOOGLEFINANCE)에만 있다. 여기서는 패턴만 Code.gs 와
# 글자 그대로 맞춰 두고(check_port 가 대조), parse_message 는 이 문자를 실패로 돌려보낸다.
_FOREIGN_RE = re.compile(
    r'^(?P<card>.{1,20}?)\s*'
    r'(?P<kind>해외(?:승인|취소)(?:\s*취소)?)\s+'
    r'(?P<name>\S+?)\s+'
    r'(?P<mmdd>\d{1,2}/\d{1,2})(?:\s+(?P<hm>\d{1,2}:\d{2}))?\s+'
    r'(?P<cur>[A-Z]{3})\s*(?P<famt>\d[\d,]*(?:\.\d+)?)'
    r'\s*(?P<merchant>.*)$'
)


def _normalize(text: str) -> str:
    """[Web 발신] 제거 + 줄바꿈/공백 정리."""
    text = re.sub(r'\[Web\s*발신\]', ' ', text or "")
    return re.sub(r'\s+', ' ', text).strip()


# 가맹점명 뒤에 붙는 꼬리표. 카드사가 "카카오T일반 누적732,232원" 처럼 보낸다.
# 이걸 안 떼면 결제할 때마다 누적액이 달라져 매번 다른 가맹점으로 인식되고,
# 고정비 자동 감지·태그 학습·중복 방지가 전부 무력해진다.
_TRAILING_RE = re.compile(r'\s*(?:누적|누계|총누적|잔액|잔여한도)\s*[\d,]+\s*원?\s*$')


def clean_merchant(merchant: str) -> str:
    """가맹점명에서 누적액 같은 꼬리표를 떼어낸다."""
    return _TRAILING_RE.sub('', merchant or "").strip()


def _resolve_year(mmdd: str, hm: str | None) -> datetime | None:
    """연도 없는 MM/DD HH:MM 을 현재연도로 보정. 미래로 튀면 작년으로 간주.

    시각이 없는 문자(취소)는 00:00 으로 본다. 날짜만 맞으면 주간 계산은 그대로 맞다.
    """
    now = datetime.now()
    try:
        month, day = (int(x) for x in mmdd.split('/'))
        hh, mm = (int(x) for x in (hm or "00:00").split(':'))
        dt = datetime(now.year, month, day, hh, mm)
    except ValueError:
        return None
    if (dt - now).days > 1:          # 예: 지금 1월인데 문자가 12월 → 작년
        # replace() 를 쓰면 안 된다. 올해가 윤년이고 문자가 2/29 면 작년엔 없는 날이라
        # ValueError 가 try 밖에서 터져 배치 전체가 죽는다. 새로 만들어서 여기서 잡는다.
        try:
            dt = datetime(now.year - 1, month, day, hh, mm)
        except ValueError:
            return None
    return dt


def parse_message(text: str) -> dict | None:
    """카드 문자 1건을 파싱. 형식이 안 맞으면 None."""
    norm = _normalize(text)
    # 카드번호가 있는 형식이 먼저. 실패하면 번호 없는 형식(현대카드)으로 한 번 더.
    m = _APPROVAL_RE.search(norm) or _APPROVAL_NO_NUM_RE.search(norm)
    if not m:
        # 외화 해외결제(_FOREIGN_RE)도 여기서는 None 이다. 원화 금액을 정할 환율이 없는데
        # 0원으로 저장하면 조용히 틀린다 — run.py 의 '파싱 실패' 목록에 떠야 사람이 넣는다.
        return None

    amount = int(m.group("amount").replace(",", ""))
    kind = m.group("kind")
    if "취소" in kind:                # '취소' / '매출취소' 둘 다
        amount = -amount

    dt = _resolve_year(m.group("mmdd"), m.group("hm"))
    # 날짜를 못 정하면 저장할 수 없다. 예전에는 datetime 을 빈 문자열로 두고 넘겼는데,
    # ledger 가 그 행을 '저장했다'고 세어놓고 정렬 단계에서 조용히 버렸다.
    # 실패로 돌려보내야 run.py 의 '파싱 실패' 목록에 떠서 사람이 알아챈다.
    if dt is None:
        return None
    merchant = clean_merchant(m.group("merchant"))

    return {
        "card": m.group("card"),
        "last4": m.groupdict().get("last4") or "",   # 번호 없는 형식에서는 빈 값
        "kind": kind,
        "name": m.group("name"),
        "amount": amount,
        "paytype": (m.group("paytype") or "").strip(),
        "datetime": dt.strftime("%Y-%m-%d %H:%M"),
        "merchant": merchant,
        "category": classify(merchant),
        "raw": norm,
    }


