    samples = [
        "[Web 발신]\n신한카드(1234)승인 홍*동 94,400원(일시불)07/01 19:55 폴리스 유한",
        "[Web 발신]\n신한카드(1234)승인 홍*동 5,500원(일시불)07/02 08:12 스타벅스 강남",
        "[Web 발신]\n신한카드(1234)취소 홍*동 12,000원(일시불)07/03 21:40 배달의민족",
        "[Web발신]\n신한카드 (1234)  매출취소  홍*동       29,902원  07/12 네이버페이",
        # 현대카드 — 카드번호가 없고 줄바꿈으로 항목이 나뉜다
        "[Web발신]\n현대카드Z ontact 승인\n홍*동\n10,000원 일시불\n07/27 17:10\n"
        "모바일티머니선\n누적206,250원",
    ]
    for s in samples:
        r = parse_message(s)
        print("-" * 60)
        if r:
            print(f"{r['datetime']} | {r['amount']:>9,}원 | {r['category']:<8} | "
                  f"{r['merchant']}  ({r['card']} {r['last4']}, {r['paytype']})")
        else:
            print("파싱 실패:", s)
